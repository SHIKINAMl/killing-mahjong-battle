        private static readonly Dictionary<HandArchetype.Info, string> NotebookTags =
            new Dictionary<HandArchetype.Info, string>
            {
                { HandArchetype.Narabi, "連番派" },
                { HandArchetype.Koutsu, "同じ3枚" },
                { HandArchetype.Hashi, "端牌派" },
                { HandArchetype.Some, "染め手" },
                { HandArchetype.Chiitoi, "ペア派" },
                { HandArchetype.Dora, "ドラ勝負" },
                { HandArchetype.Yakuman, "役満狙い" },
            };

        private static string NotebookTag(HandArchetype.Info type)
        {
            return type != null && NotebookTags.TryGetValue(type, out string tag) ? tag : null;
        }

        private static string NotebookNote(YakuExamples.Entry entry)
        {
            switch (entry.Name)
            {
                case "立直":
                case "ドラ":
                case "一発":
                case "河底撈魚": return "手の形は何でもいいわ。";
                case "平和": return ""; // 待ちは先輩メモで説明する。
                case "赤ドラ": return "赤い5は、この3枚よ。";
                case "緑一色": return "この卓に發はないわ。";
                case "純正九蓮宝燈": return ""; // 当たり牌は先輩メモで説明する。
                default: return YakuExamples.NoteOf(entry);
            }
        }
